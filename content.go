func GetUpcomingPrograms() []WellnessProgram {
	now := time.Now().UTC()
	today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)

	programs := make([]WellnessProgram, len(ProgramSeeds))
	for i, seed := range ProgramSeeds {
		startTime := today.AddDate(0, 0, seed.DaysOffset).Add(time.Duration(seed.HourUTC)*time.Hour + time.Duration(seed.MinuteUTC)*time.Minute)
		startUTC := startTime.Format(time.RFC3339)
		searchText := strings.ToLower(fmt.Sprintf("%s %s %s %s %s %s %s %s",
			seed.Title, seed.Organizer, seed.Category, seed.City, seed.Country, seed.Format, seed.Price, seed.Language))
		regURL := fmt.Sprintf("mailto:contact@joyfulbeing.in?subject=Register%%20for%%20%s", strings.ReplaceAll(seed.Title, " ", "%20"))

		programs[i] = WellnessProgram{
			Title:           seed.Title,
			Organizer:       seed.Organizer,
			Category:        seed.Category,
			Country:         seed.Country,
			City:            seed.City,
			Format:          seed.Format,
			Price:           seed.Price,
			Language:        seed.Language,
			StartUTC:        startUTC,
			Duration:        seed.Duration,
			Description:     seed.Description,
			RegistrationURL: regURL,
			Audience:        seed.Audience,
			Verified:        seed.Verified,
			SearchText:      searchText,
		}
	}
	return programs
}

var WellnessPrograms = GetUpcomingPrograms()
